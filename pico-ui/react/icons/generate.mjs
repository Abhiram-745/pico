#!/usr/bin/env node
// Explicit allowlist: never traverse the workspace or read environment files.
import { readFile, writeFile } from 'node:fs/promises';
const names = ['claude', 'codex', 'chrome', 'lovable', 'grok', 'cursor', 'vscode', 'chatgpt', 'busy', 'dot', 'tick', 'cross', 'attention', 'ready'];
const lines = ['/* Generated by node pico-ui/react/icons/generate.mjs; edit the SVG sources. */', ':root {'];
for (const name of names) {
  const svg = (await readFile(new URL(`${name}.svg`, import.meta.url), 'utf8')).trim();
  if (!svg.includes('viewBox="0 0 24 24"') || /<(?:script|image|animate|style)\b|\bon\w+=|\bhref=/i.test(svg)) throw new Error(`Invalid static icon: ${name}`);
  // Percent-encode quotes, hashes, angle brackets and all other URI punctuation.
  const uri = encodeURIComponent(svg).replace(/[!'()*]/g, c => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);
  lines.push(`  --icon-${name}: url("data:image/svg+xml,${uri}");`);
}
lines.push('}', '');
const output = new URL('../icons.css', import.meta.url);
const css = lines.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== css) throw new Error('icons.css is stale; run this script without --check');
  console.log(`Validated ${names.length} generated masks.`);
} else {
  await writeFile(output, css);
  console.log(`Generated ${names.length} masks.`);
}
